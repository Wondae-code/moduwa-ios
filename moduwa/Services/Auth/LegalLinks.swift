import Foundation

/// 약관·개인정보 처리방침이 어디에 있는지 한곳에서 정한다.
///
/// **개인정보 처리방침만 URL 이다.** 앱스토어가 메타데이터에 방침 URL 을 필수로 요구하고,
/// 방침은 회사가 언제든 고칠 수 있어야 해서 웹에 두는 것이 맞다. 약관은 번들 텍스트로
/// 앱 안에서 읽는다(`TermsView`) — 그쪽은 URL 요구가 없고, 오프라인에서도 읽혀야 한다.
enum LegalLinks {
    /// 개인정보 처리방침. 서버가 `/privacy` 로 띄운다(2026-09-05 확인 — 200, 시행일
    /// 2026-09-02, 민감정보 별도 안내 포함). nil 이면 앱이 "준비 중" 을 알리고 링크를 열지
    /// 않는다 — 없는 주소로 보내면 브라우저 오류 페이지가 뜨고, 그것은 방침이 없는 것보다
    /// 나쁘게 읽힌다.
    static let privacyPolicy: URL? = URL(string: "https://moduwa.app/privacy")

    /// 문의 창구. **고객센터 화면이 이 값을 쓴다** — 심사(1.2)가 연락 수단 공개를 요구한다.
    /// 처리방침·약관 본문이 `help@moduwa.app` 을 안내하고 있다(2026-09-05 확인).
    /// ⚠️ 아직 화면에 연결하지 않았다 — 고객센터는 여전히 "준비 중" 이다.
    static let supportEmail: String? = nil
}
